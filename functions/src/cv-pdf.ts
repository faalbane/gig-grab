import { Request } from "firebase-functions/v2/https";
import type { Response } from "express";
import PDFDocument from "pdfkit";
import {
  db,
  candidates,
  sessions,
  profileCards,
  type ProfileProject,
} from "@gig-grab/db";
import { eq } from "drizzle-orm";
import { verifySessionToken } from "./security";

type Card = {
  name: string | null;
  title: string | null;
  yearsExperience: number | null;
  location: string | null;
  summary: string | null;
  ticketsAndCards: string[];
  recentProjects: ProfileProject[];
  email?: string | null;
  phone?: string | null;
};

function clean(s: string | null | undefined): string {
  if (!s) return "";
  const t = String(s).trim();
  if (!t || t === "<UNKNOWN>" || t.toLowerCase() === "unknown") return "";
  return t;
}

function renderPdf(card: Card): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: "LETTER", margin: 56 });
    const chunks: Buffer[] = [];
    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const name = clean(card.name) || "GigGrab candidate";
    const trade = clean(card.title);
    const years = card.yearsExperience ?? 0;
    const headerLine = [trade, years > 0 ? `${years} years` : null]
      .filter(Boolean)
      .join(" · ");

    // Top: name + role line
    doc.fillColor("#111827").font("Helvetica-Bold").fontSize(28).text(name);
    doc.moveDown(0.3);
    if (headerLine) {
      doc.font("Helvetica").fontSize(12).fillColor("#374151").text(headerLine);
    }
    const contactBits = [
      clean(card.location),
      clean(card.email ?? null),
      clean(card.phone ?? null),
    ].filter(Boolean);
    if (contactBits.length) {
      doc
        .moveDown(0.1)
        .fillColor("#6b7280")
        .fontSize(10)
        .text(contactBits.join(" · "));
    }

    // Profile summary
    const summary = clean(card.summary);
    if (summary) {
      doc.moveDown(1);
      doc
        .fillColor("#6b7280")
        .font("Helvetica-Bold")
        .fontSize(9)
        .text("PROFILE", { characterSpacing: 1.4 });
      doc
        .moveDown(0.4)
        .fillColor("#1f2937")
        .font("Helvetica")
        .fontSize(11)
        .text(summary, { lineGap: 3 });
    }

    // Tickets & cards
    if (card.ticketsAndCards.length) {
      doc.moveDown(1);
      doc
        .fillColor("#6b7280")
        .font("Helvetica-Bold")
        .fontSize(9)
        .text("TICKETS & CARDS", { characterSpacing: 1.4 });
      doc.moveDown(0.4).fillColor("#1f2937").font("Helvetica").fontSize(11);
      card.ticketsAndCards.forEach((t) => {
        doc.text(`• ${clean(t)}`);
      });
    }

    // Recent projects
    if (card.recentProjects.length) {
      doc.moveDown(1);
      doc
        .fillColor("#6b7280")
        .font("Helvetica-Bold")
        .fontSize(9)
        .text("RECENT PROJECTS", { characterSpacing: 1.4 });
      card.recentProjects.forEach((p) => {
        doc.moveDown(0.5);
        const role = clean(p.role);
        const company = clean(p.company);
        const period = clean(p.period);
        const desc = clean(p.description ?? null);
        doc
          .fillColor("#111827")
          .font("Helvetica-Bold")
          .fontSize(11)
          .text([role, company].filter(Boolean).join(" — "));
        if (period) {
          doc.fillColor("#6b7280").font("Helvetica").fontSize(10).text(period);
        }
        if (desc) {
          doc
            .moveDown(0.2)
            .fillColor("#1f2937")
            .font("Helvetica")
            .fontSize(11)
            .text(desc, { lineGap: 2 });
        }
      });
    }

    // Footer
    doc
      .moveDown(2)
      .fillColor("#9ca3af")
      .font("Helvetica")
      .fontSize(8)
      .text("Generated by GigGrab — gig-grab.web.app", {
        align: "center",
      });

    doc.end();
  });
}

/**
 * GET /api/sessions/:id/cv.pdf?token=…
 *
 * Renders the candidate's profile_card to a PDF. Requires the same HMAC
 * session token that gates /sessions/:id/profile.
 */
export async function sessionCvPdf(
  req: Request,
  res: Response,
  sessionId: string,
): Promise<void> {
  const token = (req.query.token as string | undefined) ?? "";
  if (!verifySessionToken(sessionId, token)) {
    res.status(401).json({ error: "invalid or missing session token" });
    return;
  }

  const [s] = await db()
    .select({ id: sessions.id, candidateId: sessions.candidateId })
    .from(sessions)
    .where(eq(sessions.id, sessionId))
    .limit(1);
  if (!s?.candidateId) {
    res.status(404).json({ error: "session has no candidate" });
    return;
  }

  const [card] = await db()
    .select()
    .from(profileCards)
    .where(eq(profileCards.candidateId, s.candidateId))
    .limit(1);
  const [cand] = await db()
    .select({ phone: candidates.phone, email: candidates.email })
    .from(candidates)
    .where(eq(candidates.id, s.candidateId))
    .limit(1);
  if (!card) {
    res.status(404).json({ error: "no profile yet — call hasn't been processed" });
    return;
  }

  const buf = await renderPdf({
    name: card.name,
    title: card.title,
    yearsExperience: card.yearsExperience,
    location: card.location,
    summary: card.summary,
    ticketsAndCards: card.ticketsAndCards ?? [],
    recentProjects: card.recentProjects ?? [],
    email: cand?.email ?? null,
    phone: cand?.phone?.startsWith("pending-") ? null : cand?.phone ?? null,
  });

  const safeName = (clean(card.name) || "candidate")
    .replace(/[^A-Za-z0-9]+/g, "_")
    .toLowerCase();
  res
    .status(200)
    .set({
      "Content-Type": "application/pdf",
      "Content-Disposition": `attachment; filename="${safeName}_giggrab.pdf"`,
      "Cache-Control": "private, max-age=60",
      "Content-Length": String(buf.length),
    })
    .send(buf);
}
